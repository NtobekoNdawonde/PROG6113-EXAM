    private void btnCalculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalculateActionPerformed
try {
    int quantity = Integer.parseInt(txtQuantity.getText());
    double price = Double.parseDouble(txtPrice.getText());

    double productPrice = quantity * price;

    double vat = productPrice * 0.15;
    double commission = productPrice * 0.05;

    double total = productPrice + vat + commission;

    txtVAT.setText(String.format("%.2f", vat));
    txtCommission.setText(String.format("%.2f", commission));
    txtTotal.setText(String.format("%.2f", total));

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Please enter valid quantity and price.");
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnCalculateActionPerformed

    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
 try {
    java.io.FileWriter writer = new java.io.FileWriter("MattressSales.txt", true);

    writer.write("Mattress: " + cmbMattress.getSelectedItem() + "\n");
    writer.write("Quantity: " + txtQuantity.getText() + "\n");
    writer.write("Price: " + txtPrice.getText() + "\n");
    writer.write("VAT: " + txtVAT.getText() + "\n");
    writer.write("Commission: " + txtCommission.getText() + "\n");
    writer.write("Total: " + txtTotal.getText() + "\n");
    writer.write("--------------------------\n");

    writer.close();

    javax.swing.JOptionPane.showMessageDialog(this,
            "Sale saved successfully!");

} catch (java.io.IOException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Error saving sale.");
}       // TODO add your handling code here:
    }//GEN-LAST:event_btnSaveActionPerformed

